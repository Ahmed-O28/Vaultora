package com.banking.systemdesign.idgenerator;

import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.context.annotation.Primary;
import org.springframework.stereotype.Component;

import java.time.Instant;
import java.util.function.LongSupplier;

/**
 * Production-grade Unique ID Generator (Twitter Snowflake layout).
 *
 * <pre>
 *  | 41 bits : ms since custom epoch | 10 bits : node id | 12 bits : sequence |
 * </pre>
 *
 * Guarantees:
 * <ul>
 *   <li>Unique per node: up to 4096 ids per millisecond, then the generator waits for the next millisecond
 *       (the sequence can never wrap around inside the same millisecond).</li>
 *   <li>Unique across nodes: every node must be configured with a different {@code app.idgen.node-id} (0-1023).</li>
 *   <li>Time ordered: ids sort by creation time, which keeps database indexes efficient.</li>
 *   <li>Clock safe: if the system clock moves backwards the generator waits (small drift) or fails fast (large drift)
 *       instead of ever issuing a duplicate.</li>
 *   <li>Lock free for the database: no sequence table, no round trip.</li>
 * </ul>
 *
 * Identifier format: {@code PREFIX-<snowflake>} e.g. {@code TXN-7254849302817280001}, {@code BILL-7254849302817280002}.
 *
 * It is marked {@link Primary} so that services that depend on {@link UniqueIdGenerator} use it automatically.
 */
@Component
@Primary
public class DistributedSnowflakeIdGenerator implements UniqueIdGenerator {

    /** 2024-01-01T00:00:00Z */
    public static final long CUSTOM_EPOCH = 1704067200000L;

    private static final int NODE_BITS = 10;
    private static final int SEQUENCE_BITS = 12;
    private static final long MAX_NODE_ID = (1L << NODE_BITS) - 1;
    private static final long SEQUENCE_MASK = (1L << SEQUENCE_BITS) - 1;
    private static final long MAX_BACKWARD_WAIT_MS = 5000L;

    private final long nodeId;
    private final LongSupplier clock;

    private long lastTimestamp = -1L;
    private long sequence = 0L;

    @Autowired
    public DistributedSnowflakeIdGenerator(@Value("${app.idgen.node-id:1}") int nodeId) {
        this(nodeId, System::currentTimeMillis);
    }

    /** Visible for tests: allows a controllable clock. */
    public DistributedSnowflakeIdGenerator(int nodeId, LongSupplier clock) {
        if (nodeId < 0 || nodeId > MAX_NODE_ID) {
            throw new IllegalArgumentException("node id must be between 0 and " + MAX_NODE_ID);
        }
        this.nodeId = nodeId;
        this.clock = clock;
    }

    @Override
    public String generateId(String prefix) {
        return sanitizePrefix(prefix) + "-" + nextId();
    }

    /** Generates the raw 64-bit identifier. */
    public synchronized long nextId() {
        long now = clock.getAsLong();

        if (now < lastTimestamp) {
            // The clock moved backwards. Wait for it to catch up when the drift is small, otherwise refuse.
            long drift = lastTimestamp - now;
            if (drift > MAX_BACKWARD_WAIT_MS) {
                throw new IllegalStateException("System clock moved backwards by " + drift + " ms; refusing to generate ids");
            }
            now = waitUntil(lastTimestamp);
        }

        if (now == lastTimestamp) {
            sequence = (sequence + 1) & SEQUENCE_MASK;
            if (sequence == 0) {
                // Sequence exhausted for this millisecond: wait for the next one.
                now = waitUntil(lastTimestamp + 1);
            }
        } else {
            sequence = 0L;
        }

        lastTimestamp = now;
        return ((now - CUSTOM_EPOCH) << (NODE_BITS + SEQUENCE_BITS))
                | (nodeId << SEQUENCE_BITS)
                | sequence;
    }

    private long waitUntil(long targetMillis) {
        long now = clock.getAsLong();
        while (now < targetMillis) {
            Thread.onSpinWait();
            now = clock.getAsLong();
        }
        return now;
    }

    /** Upper-cases the prefix and keeps only A-Z / 0-9 (max 8 chars); falls back to "ID". */
    public static String sanitizePrefix(String prefix) {
        if (prefix == null) {
            return "ID";
        }
        StringBuilder sb = new StringBuilder();
        for (char c : prefix.toUpperCase().toCharArray()) {
            if ((c >= 'A' && c <= 'Z') || (c >= '0' && c <= '9')) {
                sb.append(c);
                if (sb.length() == 8) {
                    break;
                }
            }
        }
        return sb.length() == 0 ? "ID" : sb.toString();
    }

    /** Decodes an identifier generated by this class. Throws IllegalArgumentException when the format is wrong. */
    public static IdInfo parse(String id) {
        if (id == null) {
            throw new IllegalArgumentException("id is required");
        }
        int dash = id.lastIndexOf('-');
        if (dash <= 0 || dash == id.length() - 1) {
            throw new IllegalArgumentException("Invalid id format, expected PREFIX-<number>");
        }
        String prefix = id.substring(0, dash);
        long numeric;
        try {
            numeric = Long.parseLong(id.substring(dash + 1));
        } catch (NumberFormatException e) {
            throw new IllegalArgumentException("Invalid id format, numeric part is not a valid 64-bit number");
        }
        if (numeric < 0) {
            throw new IllegalArgumentException("Invalid id format, numeric part must be positive");
        }
        long millis = (numeric >> (NODE_BITS + SEQUENCE_BITS)) + CUSTOM_EPOCH;
        int node = (int) ((numeric >> SEQUENCE_BITS) & MAX_NODE_ID);
        int seq = (int) (numeric & SEQUENCE_MASK);
        return new IdInfo(id, prefix, numeric, Instant.ofEpochMilli(millis), node, seq);
    }
}
